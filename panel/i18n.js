function resolveLang(setting) {
  if (setting && setting !== 'auto' && SCREWED_I18N[setting]) return setting;
  const ui = (globalThis.chrome && chrome.i18n && chrome.i18n.getUILanguage && chrome.i18n.getUILanguage())
    || (globalThis.navigator && navigator.language) || 'en';
  const base = ui.toLowerCase().split(/[-_]/)[0];
  return SCREWED_I18N[base] ? base : 'en';
}

function translator(setting) {
  const dict = SCREWED_I18N[resolveLang(setting)];
  return (key, vars = {}) => (dict[key] || SCREWED_I18N.en[key] || key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
